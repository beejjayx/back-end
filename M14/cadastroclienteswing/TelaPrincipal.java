    private void limparCampos() {
        inputNome.setText("");
        inputCPF.setText("");
        inputTel.setText("");
        inputEndereco.setText("");
        inputNumero.setText("");
        inputCidade.setText("");
        inputEstado.setText("");
    }
    
    public void atualizarCadastro(Long cpf, String novoNome, Long novoTel, String novoEnd) {
        Cliente cliente = this.clienteDAO.consultar(cpf);
        
        if (cliente != null) {
            cliente.setNome(novoNome);
            cliente.setEnd(novoEnd);
            cliente.setTel(novoTel);
            
            this.clienteDAO.alterar(cliente);
            
            JOptionPane.showMessageDialog(null, "Cadastro atualizado com sucesso!.", "Sucesso",JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(null, "Cliente não encontrado.", "Erro",JOptionPane.INFORMATION_MESSAGE);
        }
    }
    

