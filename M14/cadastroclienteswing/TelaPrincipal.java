    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        int linhaSelecionada = tabelaClientes.getSelectedRow();
    
        if (linhaSelecionada >= 0) {
            Long cpf = Long.valueOf(inputCPF.getText()); 
            String novoNome = inputNome.getText();

            Cliente cliente = this.clienteDAO.consultar(cpf);

            if (cliente != null) {
                cliente.setNome(novoNome);
                this.clienteDAO.alterar(cliente); 

                tabelaClientes.setValueAt(novoNome, linhaSelecionada, 0);
                
                JOptionPane.showMessageDialog(null, "Cadastro atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(null, "Erro ao atualizar!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(null, "Nenhuma linha selecionada!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        }//GEN-LAST:event_btnAtualizarActionPerformed
        
    
